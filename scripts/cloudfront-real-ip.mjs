// Writes the nginx `set_real_ip_from` list for CloudFront's origin-facing ranges, so nginx restores the viewer's IP
// from X-Forwarded-For and per-IP rate limits apply per client instead of per CloudFront edge.
// Plain Node, no dependencies. Run as root (it writes under /etc/nginx and reloads nginx):
//
//   node scripts/cloudfront-real-ip.mjs [output]   default /etc/nginx/snippets/cloudfront-real-ip.conf
//
// The file is replaced only when the ranges change. A new file that fails `nginx -t` is rolled back. Failures log
// one JSON line with level "error" (the CloudWatch alarm in docs/ec2-setup.md section 10) and exit 1; nginx keeps the
// previous list, so the site stays up and only new edges share a rate limit until the next successful run.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { isIP } from "node:net";
import { pathToFileURL } from "node:url";

export const IP_RANGES_URL = "https://ip-ranges.amazonaws.com/ip-ranges.json";
export const DEFAULT_OUTPUT = "/etc/nginx/snippets/cloudfront-real-ip.conf";
const SERVICE = "CLOUDFRONT_ORIGIN_FACING";

function isCidr(value, family) {
  if (typeof value !== "string") return false;
  const [address, length, ...rest] = value.split("/");
  if (rest.length > 0 || !/^\d{1,3}$/.test(length ?? "")) return false;
  return isIP(address) === family && Number(length) <= (family === 4 ? 32 : 128);
}

/** The CloudFront origin-facing CIDRs in AWS's ip-ranges.json, sorted and deduplicated. Throws on a malformed file. */
export function originFacingPrefixes(ranges) {
  if (!ranges || !Array.isArray(ranges.prefixes) || !Array.isArray(ranges.ipv6_prefixes)) {
    throw new Error("ip-ranges.json has no prefixes / ipv6_prefixes arrays");
  }
  const pick = (list, key, family) => {
    const values = list.filter((entry) => entry?.service === SERVICE).map((entry) => entry[key]);
    const bad = values.find((value) => !isCidr(value, family));
    if (bad !== undefined) throw new Error(`invalid ${SERVICE} prefix: ${JSON.stringify(bad)}`);
    return [...new Set(values)].sort();
  };
  const ipv4 = pick(ranges.prefixes, "ip_prefix", 4);
  const ipv6 = pick(ranges.ipv6_prefixes, "ipv6_prefix", 6);
  // CloudFront has dozens of IPv4 ranges; a short list means AWS changed the file, not that the edges went away.
  if (ipv4.length < 10) throw new Error(`only ${ipv4.length} IPv4 ${SERVICE} prefixes; refusing to write`);
  return { ipv4, ipv6 };
}

/** The include file. Only the set_real_ip_from lines decide whether it changed (see sameRanges). */
export function renderConf({ ipv4, ipv6 }, syncToken = "") {
  return [
    "# Generated by scripts/cloudfront-real-ip.mjs from " + IP_RANGES_URL + ". Do not edit; the timer overwrites it.",
    `# ${SERVICE}, syncToken ${syncToken}: ${ipv4.length} IPv4 and ${ipv6.length} IPv6 ranges.`,
    ...ipv4.map((cidr) => `set_real_ip_from ${cidr};`),
    ...ipv6.map((cidr) => `set_real_ip_from ${cidr};`),
    "",
  ].join("\n");
}

/** True when both files trust the same ranges, ignoring comments (the syncToken changes for any AWS service). */
export function sameRanges(a, b) {
  const lines = (text) => text.split("\n").filter((line) => line.startsWith("set_real_ip_from")).join("\n");
  return lines(a) === lines(b);
}

function logLine(level, event, fields = {}) {
  const line = JSON.stringify({ ts: new Date().toISOString(), level, event, ...fields });
  if (level === "error") console.error(line);
  else console.info(line);
}

/**
 * Replaces `output` with `conf` if the ranges changed, checks the nginx config, and reloads (or rolls back).
 * @param {string} output
 * @param {string} conf
 * @param {(cmd: string, args: string[]) => unknown} [run]
 */
export function install(output, conf, run = (cmd, args) => execFileSync(cmd, args, { stdio: "inherit" })) {
  const previous = existsSync(output) ? readFileSync(output, "utf8") : null;
  if (previous !== null && sameRanges(previous, conf)) return "unchanged";

  const tmp = `${output}.tmp`;
  const backup = `${output}.previous`;
  writeFileSync(tmp, conf, { mode: 0o644 });
  if (previous !== null) writeFileSync(backup, previous, { mode: 0o644 });
  renameSync(tmp, output);
  try {
    run("nginx", ["-t", "-q"]);
  } catch (error) {
    if (previous !== null) renameSync(backup, output);
    else rmSync(output, { force: true });
    throw new Error(`nginx -t failed with the new list; kept the previous one (${error.message})`);
  }
  rmSync(backup, { force: true });
  // Not reloading on the first run: the include is created before the server block that uses it (ec2-setup section 7).
  if (previous !== null) run("systemctl", ["reload", "nginx"]);
  return previous === null ? "created" : "updated";
}

async function main() {
  const output = process.argv[2] ?? DEFAULT_OUTPUT;
  const response = await fetch(IP_RANGES_URL, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`GET ${IP_RANGES_URL} returned ${response.status}`);
  const ranges = await response.json();
  const prefixes = originFacingPrefixes(ranges);
  const result = install(output, renderConf(prefixes, ranges.syncToken));
  logLine("info", `cloudfront_ips.${result}`, { output, ipv4: prefixes.ipv4.length, ipv6: prefixes.ipv6.length });
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main().catch((error) => {
    logLine("error", "cloudfront_ips.failed", { message: error instanceof Error ? error.message : String(error) });
    process.exit(1);
  });
}
